#!/usr/bin/env python3
"""
export_v2_mem_to_c.py — load data/v2/*.mem (same order as $readmemh in tb_minicnn_v2.v)
and emit a single C header for the STM32 M4 bench (MINICNN_V2_REAL_MNIST).

Usage:
  python scripts/export_v2_mem_to_c.py
  python scripts/export_v2_mem_to_c.py --n-img 3 --out E:/Btech/Project/srip/arm/sage16_baseline/Core/Inc/minicnn_v2_mnist_data.h

Default: all 200 images (matches +define+REAL_MNIST N_IMG=200 in sim). Use --n-img 3
for a smaller binary during bring-up; per-image DWT is identical for the C loops.
"""
from __future__ import annotations

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = ROOT / "data" / "v2"


def hex16_to_i16(s: str) -> int:
    s = s.strip()
    if not s:
        raise ValueError("empty line in .mem")
    v = int(s, 16) & 0xFFFF
    if v & 0x8000:
        v -= 0x10000
    return v


def read_mem_int16(path: Path) -> list[int]:
    return [hex16_to_i16(line) for line in path.read_text().splitlines() if line.strip()]


def emit_array(f, ctype: str, name: str, values: list[int], per_line: int = 8) -> None:
    f.write(f"static const {ctype} {name}[{len(values)}] = {{\n")
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        f.write("  " + ", ".join(str(v) for v in chunk) + ",\n")
    f.write("};\n\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--v2-dir", type=Path, default=DATA, help="Path to data/v2")
    ap.add_argument(
        "--n-img",
        type=int,
        default=None,
        help="First N images/labels only (default: all in images.mem)",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=ROOT / "arm" / "sage16_baseline" / "Core" / "Inc" / "minicnn_v2_mnist_data.h",
    )
    args = ap.parse_args()
    d = args.v2_dir

    c1 = read_mem_int16(d / "conv1_k.mem")
    c2 = read_mem_int16(d / "conv2_k.mem")
    w1 = read_mem_int16(d / "w1.mem")
    w2 = read_mem_int16(d / "w2.mem")
    img_flat = read_mem_int16(d / "images.mem")
    labels = read_mem_int16(d / "labels.mem")

    expect_c1, expect_c2 = 8 * 9, 16 * 8 * 9
    if len(c1) != expect_c1 or len(c2) != expect_c2:
        raise SystemExit(
            f"conv size mismatch: c1={len(c1)} (want {expect_c1}), c2={len(c2)} (want {expect_c2})"
        )
    if len(w1) != 32 * 256 or len(w2) != 12 * 32:
        raise SystemExit(f"FC mem size w1={len(w1)} w2={len(w2)}")

    per_img = 26 * 26
    n_file = len(img_flat) // per_img
    if len(img_flat) != n_file * per_img:
        raise SystemExit(f"images.mem length {len(img_flat)} not multiple of {per_img}")
    if len(labels) < n_file:
        raise SystemExit("labels.mem shorter than image count")
    n_img = args.n_img if args.n_img is not None else n_file
    n_img = min(n_img, n_file, len(labels))
    img_flat = img_flat[: n_img * per_img]
    labels = labels[:n_img]

    out = args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        f.write(
            "/* Auto-generated by scripts/export_v2_mem_to_c.py — do not edit. */\n"
            "#ifndef MINICNN_V2_MNIST_DATA_H\n"
            "#define MINICNN_V2_MNIST_DATA_H\n"
            "#include <stdint.h>\n\n"
        )
        f.write(
            "/* same bytes as data/v2/ *.mem files / tb_minicnn_v2.v +define+REAL_MNIST */\n"
            f"#define MINICNN_V2_N_IMG ({n_img})\n\n"
        )
        emit_array(f, "int16_t", "minicnn_v2_conv1_k", c1)
        emit_array(f, "int16_t", "minicnn_v2_conv2_k", c2)
        emit_array(f, "int16_t", "minicnn_v2_w1", w1)
        emit_array(f, "int16_t", "minicnn_v2_w2", w2)
        emit_array(f, "int16_t", "minicnn_v2_img", img_flat)
        emit_array(f, "int16_t", "minicnn_v2_labels", labels)
        f.write("#endif\n")
    print(f"  wrote {out}  (N_IMG={n_img}, img_words={len(img_flat)})\n")


if __name__ == "__main__":
    main()
