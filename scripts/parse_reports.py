#!/usr/bin/env python3
"""
parse_reports.py -- consolidate Vivado + simulation artefacts into the
four markdown tables the paper pulls its numbers from.

Reads:
    reports/<top>/util.rpt         post-route utilization (Vivado)
    reports/<top>/timing.rpt       post-route timing summary (Vivado)
    reports/<top>/power.rpt        post-route power (Vivado)
    build/regression.log           output of scripts/run_sim.bat

Writes:
    reports/area_comparison.md
    reports/latency_table.md
    reports/power.md
    reports/regression_summary.md

If Vivado hasn't run yet, the Vivado-derived rows are written as 'N/A'
with a prompt telling the user to run scripts/synth_all.bat.
"""
import os, re, sys, glob
from pathlib import Path

ROOT     = Path(__file__).resolve().parents[1]
REPORTS  = ROOT / "reports"
BUILD    = ROOT / "build"

TOPS = [
    ("matmul_sage16",     "single-kernel matmul only"),
    ("conv3x3_sage16",    "single-kernel conv only"),
    ("quat_sage16",       "single-kernel quat only"),
    ("sage16_top",        "shared fabric -- paper headline"),
    ("sage16_mmio",       "old MMIO wrapper (matmul only)"),
    ("sage16_mmio_top",   "new MMIO wrapper (multi-kernel)"),
    ("sage16_pcpi",       "old PCPI wrapper (matmul only)"),
    ("sage16_pcpi_top",   "new PCPI wrapper (multi-kernel)"),
]

# ---- regexes tuned to Vivado 2020+ report layouts ----
RE_UTIL = {
    # look for "| <resource> | <used> |" rows in the utilization summary.
    # The asterisk on "Slice LUTs*" was dropped in Vivado 2024+, so allow
    # either form. Only match the FIRST occurrence (top-level summary).
    "LUT"    : re.compile(r"\|\s*(?:Slice LUTs\*?|CLB LUTs)\s+\|\s*(\d+)\s*\|"),
    "FF"     : re.compile(r"\|\s*(?:Slice Registers|CLB Registers)\s+\|\s*(\d+)\s*\|"),
    "DSP"    : re.compile(r"\|\s*DSPs\s+\|\s*(\d+)\s*\|"),
    "BRAM"   : re.compile(r"\|\s*Block RAM Tile\s+\|\s*(\d+(?:\.\d+)?)\s*\|"),
}
RE_WNS  = re.compile(r"WNS\(ns\).*?(-?\d+\.\d+)", re.S)
RE_PER  = re.compile(r"Requirement:\s*(\d+\.\d+)\s*ns")
RE_PWR_TOTAL   = re.compile(r"Total On-Chip Power \(W\)\s*\|\s*([\d\.]+)")
RE_PWR_DYNAMIC = re.compile(r"Dynamic \(W\)\s*\|\s*([\d\.]+)")
RE_PWR_STATIC  = re.compile(r"Device Static \(W\)\s*\|\s*([\d\.]+)")


def read(path):
    try:
        return Path(path).read_text(errors="ignore")
    except FileNotFoundError:
        return None


def parse_util(text):
    if not text: return {}
    out = {}
    for name, rx in RE_UTIL.items():
        m = rx.search(text)
        out[name] = m.group(1) if m else None
    return out


def parse_timing(text):
    """Returns (WNS_ns, clock_period_ns). Fmax = 1000/(period - WNS)."""
    if not text: return (None, None)
    m_wns = RE_WNS.search(text)
    m_per = RE_PER.search(text)
    wns    = float(m_wns.group(1)) if m_wns else None
    period = float(m_per.group(1)) if m_per else None
    return (wns, period)


def fmax_mhz(wns, period):
    if wns is None or period is None: return None
    achievable = period - wns   # if wns negative, achievable > period
    if achievable <= 0: return None
    return 1000.0 / achievable


def parse_power(text):
    if not text: return (None, None, None)
    m_t = RE_PWR_TOTAL.search(text)
    m_d = RE_PWR_DYNAMIC.search(text)
    m_s = RE_PWR_STATIC.search(text)
    t = float(m_t.group(1)) if m_t else None
    d = float(m_d.group(1)) if m_d else None
    s = float(m_s.group(1)) if m_s else None
    return (t, d, s)


def fmt(v, fmt_str="{}"):
    if v is None: return "N/A"
    try:
        return fmt_str.format(v)
    except (ValueError, TypeError):
        return str(v)


# ---------------------------------------------------------------------------
def collect(top):
    base = REPORTS / top
    u   = parse_util  (read(base / "util.rpt"))
    tw  = parse_timing(read(base / "timing.rpt"))
    pw  = parse_power (read(base / "power.rpt"))
    return {
        "util": u,
        "wns":  tw[0],
        "period": tw[1],
        "fmax": fmax_mhz(*tw),
        "p_total": pw[0],
        "p_dynamic": pw[1],
        "p_static":  pw[2],
    }


def write_area_comparison(stats):
    lines = []
    lines.append("# Area comparison (post-route, Artix-7 xc7a35t)\n")
    lines.append("_Auto-generated by `scripts/parse_reports.py`._\n")
    lines.append("| top | desc | LUT | FF | DSP | BRAM | Fmax (MHz) |")
    lines.append("|-----|------|----:|---:|----:|-----:|-----------:|")
    for top, desc in TOPS:
        s = stats[top]
        u = s["util"]
        lines.append("| `{t}` | {d} | {l} | {f} | {dsp} | {b} | {fm} |".format(
            t=top, d=desc,
            l=fmt(u.get("LUT")),
            f=fmt(u.get("FF")),
            dsp=fmt(u.get("DSP")),
            b=fmt(u.get("BRAM")),
            fm=fmt(s["fmax"], "{:.1f}"),
        ))
    lines.append("")
    # reconfig overhead row (only meaningful if both sage16_top and the 3
    # single-kernel tops have numbers)
    try:
        sum_lut = sum(int(stats[k]["util"]["LUT"]) for k in
                      ("matmul_sage16","conv3x3_sage16","quat_sage16"))
        sum_dsp = sum(int(stats[k]["util"]["DSP"]) for k in
                      ("matmul_sage16","conv3x3_sage16","quat_sage16"))
        top_lut = int(stats["sage16_top"]["util"]["LUT"])
        top_dsp = int(stats["sage16_top"]["util"]["DSP"])
        lines.append("## Shared-fabric savings\n")
        lines.append(f"- sum-of-3-separate: LUT={sum_lut}  DSP={sum_dsp}")
        lines.append(f"- sage16_top:          LUT={top_lut}  DSP={top_dsp}")
        lines.append(f"- LUT reduction:     {100*(1 - top_lut/sum_lut):.1f}%")
        lines.append(f"- DSP reduction:     {100*(1 - top_dsp/sum_dsp):.1f}%")
    except (TypeError, KeyError, ValueError, ZeroDivisionError):
        lines.append("\n_Run `scripts/synth_all.bat` to populate the numbers above._")
    (REPORTS / "area_comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("  wrote reports/area_comparison.md")


def _scrape_minicnn(log):
    """Return dict with all MiniCNN-v1 stats or None.

    Keys:  conv1, fc1, fc2, pool, fab_i, full_i, n_img,
           mnist_correct, mnist_total, mnist_acc (or None if synthetic mode)
    """
    if not log: return None
    m = re.search(
        r"fabric compute cycles\s*:\s*Conv1=(\d+)\s+FC1=(\d+)\s+FC2=(\d+)",
        log)
    if not m: return None
    c1, f1, f2 = (int(x) for x in m.groups())
    mp = re.search(r"host SW cycles \(pool\)\s*:\s*(\d+)", log)
    pool = int(mp.group(1)) if mp else None
    mi = re.search(r"per-image avg\s*:\s*fabric=(\d+)\s+full=(\d+)", log)
    fab_i, full_i = (int(x) for x in mi.groups()) if mi else (None, None)
    mn = re.search(r"totals over (\d+) images", log)
    n_img = int(mn.group(1)) if mn else None
    # MNIST top-1 line is only present in REAL_MNIST mode
    mc = re.search(
        r"MNIST top-1.*?:\s*(\d+)\s*/\s*(\d+)\s*\(([\d\.]+)%\s*accuracy\)",
        log, re.S)
    if mc:
        mn_correct, mn_total = int(mc.group(1)), int(mc.group(2))
        mn_acc = float(mc.group(3))
    else:
        mn_correct = mn_total = mn_acc = None
    return {
        "conv1": c1, "fc1": f1, "fc2": f2, "pool": pool,
        "fab_i": fab_i, "full_i": full_i, "n_img": n_img,
        "mnist_correct": mn_correct, "mnist_total": mn_total,
        "mnist_acc": mn_acc,
    }


