def _scrape_madgwick(log):
    """Return (fab_per_step, sw_per_step, total_per_step_us) or None."""
    if not log: return None
    m = re.search(r"avg (\d+) cy/step.*?avg (\d+) cy/step", log, re.S)
    if not m: return None
    fab, sw = int(m.group(1)), int(m.group(2))
    mt = re.search(r"total\s+([\d\.]+)\s*us", log)
    us = float(mt.group(1)) if mt else None
    return (fab, sw, us)


def write_latency_table():
    # Static per-kernel numbers come from sage16_top FSM (compile-time).
    # End-to-end CNN and filter numbers are scraped from build/regression.log
    # so they refresh automatically after every regression run.
    rows = [
        # kernel,       compute,  e2e (MMIO),  reconfig gap
        ("matmul 4x4 (unsigned)", "11", "13 (MMIO) / 13 (PCPI)", "0 (hot-restart)"),
        ("matmul 4x4 (signed, MMS)", "11", "13 (MMIO) / 13 (PCPI)", "0 (hot-restart)"),
        ("conv3x3 6x6",           "16", "18 (MMIO) / 18 (PCPI)", "0 (hot-restart)"),
        ("quat 1x4x4",            "11", "13 (MMIO) / 13 (PCPI)", "0 (hot-restart)"),
        ("b2b seq (mm+conv+qt)",  "33", "35 (MMIO)",             "1 cy (S_DONE->S_CFG)"),
        ("matmul 8x8 tiled",      "80", "88",                    "n/a"),
        ("matmul 16x16 tiled",    "640","704",                   "n/a"),
    ]
    lines = ["# Latency table (simulated, cycle-accurate)\n"]
    lines.append("_Auto-generated by `scripts/parse_reports.py`._\n")
    lines.append("| kernel | compute cy | end-to-end cy | reconfig gap |")
    lines.append("|--------|-----------:|--------------:|-------------:|")
    for k,c,e,r in rows:
        lines.append(f"| {k} | {c} | {e} | {r} |")
    lines.append("")
    lines.append("- `compute cy`: start-pulse to final c_reg write (fabric busy).")
    lines.append("- `end-to-end cy`: includes bus handshake (STATUS poll or PCPI wait).")
    lines.append("- `reconfig gap`: idle cycles between two kernels on sage16_top.")

    # --- end-to-end CNN + Madgwick (scraped from build/*.log) ---
    log        = read(BUILD / "regression.log")
    log_mn     = read(BUILD / "minicnn_mnist.log")
    log_v2     = read(BUILD / "minicnn_v2.log")
    log_v2_mn  = read(BUILD / "minicnn_v2_mnist.log")
    # Prefer dedicated MNIST runs over the synthetic regression entries.
    mini    = _scrape_minicnn(log_mn) or _scrape_minicnn(log)
    mini_v2 = _scrape_minicnn_v2(log_v2_mn) or _scrape_minicnn_v2(log_v2) \
              or _scrape_minicnn_v2(log)
    mg      = _scrape_madgwick(log)
    lines.append("")
    lines.append("## End-to-end application cycle counts\n")
    lines.append("| workload | layer / step | fabric cy | SW cy | notes |")
    lines.append("|----------|--------------|----------:|------:|-------|")
    if mini:
        n_img = mini["n_img"] or 1
        c1, f1, f2 = mini["conv1"], mini["fc1"], mini["fc2"]
        pool       = mini["pool"]
        fabi       = mini["fab_i"]
        fulli      = mini["full_i"]
        lines.append(f"| MiniCNN-v1 | Conv1 (3x3, 1->4) | {c1//n_img} | 0 | 144 conv3x3 calls/img |")
        lines.append(f"| MiniCNN-v1 | AvgPool 4x4       | 0 | {pool//n_img if pool else 'N/A'} | SW on host model |")
        lines.append(f"| MiniCNN-v1 | FC1 (144->32)     | {f1//n_img} | 0 | 288 signed matmul calls/img |")
        lines.append(f"| MiniCNN-v1 | FC2 (32->12)      | {f2//n_img} | 0 | 24 signed matmul calls/img |")
        sw_avg = (fulli - fabi) if (fulli is not None and fabi is not None) else None
        us_full = (fulli/160.0) if fulli is not None else 0
        lines.append(f"| MiniCNN-v1 | **total / image** | **{fabi}** | **{sw_avg if sw_avg is not None else 'N/A'}** | {us_full:.1f} us @ 160 MHz |")
        if mini["mnist_acc"] is not None:
            lines.append(f"| MiniCNN-v1 | **MNIST top-1**   | {mini['mnist_correct']}/{mini['mnist_total']} | --- | **{mini['mnist_acc']:.2f}% accuracy on real MNIST** |")
    else:
        lines.append("| MiniCNN-v1 | *(not run)* | N/A | N/A | run `scripts/run_sim.bat minicnn` |")
    if mini_v2:
        n_img = mini_v2["n_img"] or 1
        c1, c2, f1, f2 = mini_v2["conv1"], mini_v2["conv2"], mini_v2["fc1"], mini_v2["fc2"]
        pool   = mini_v2["pool"]
        fabi   = mini_v2["fab_i"]
        fulli  = mini_v2["full_i"]
        lines.append(f"| MiniCNN-v2 | Conv1 (3x3, 1->8) | {c1//n_img} | 0 | 288 conv3x3 calls/img |")
        lines.append(f"| MiniCNN-v2 | AvgPool 4x4       | 0 | {pool//n_img if pool else 'N/A'} | SW on host model |")
        lines.append(f"| MiniCNN-v2 | Conv2 (3x3, 8->16)| {c2//n_img} | 0 | 128 conv3x3 calls/img (multi-ch sum SW) |")
        lines.append(f"| MiniCNN-v2 | FC1 (256->32)     | {f1//n_img} | 0 | 512 signed matmul calls/img |")
        lines.append(f"| MiniCNN-v2 | FC2 (32->12)      | {f2//n_img} | 0 | 24 signed matmul calls/img |")
        sw_avg = (fulli - fabi) if (fulli is not None and fabi is not None) else None
        us_full = (fulli/160.0) if fulli is not None else 0
        lines.append(f"| MiniCNN-v2 | **total / image** | **{fabi}** | **{sw_avg if sw_avg is not None else 'N/A'}** | {us_full:.1f} us @ 160 MHz |")
        if mini_v2["mnist_acc"] is not None:
            lines.append(f"| MiniCNN-v2 | **MNIST top-1**   | {mini_v2['mnist_correct']}/{mini_v2['mnist_total']} | --- | **{mini_v2['mnist_acc']:.2f}% accuracy on real MNIST** |")
    else:
        lines.append("| MiniCNN-v2 | *(not run)* | N/A | N/A | run `scripts/run_sim.bat minicnn-v2-mnist` |")
    if mg:
        fab, sw, us = mg
        lines.append(f"| Madgwick   | per IMU sample    | {fab} | {sw} | {us:.2f} us @ 160 MHz, 100 Hz IMU loop |")
    else:
        lines.append("| Madgwick   | *(not run)*       | N/A | N/A | run `scripts/run_sim.bat madgwick` |")

    # --- frozen M4 DWT (manual record; do not let regeneration drop it) ---
    frozen = REPORTS / "m4_dwt_frozen.md"
    if frozen.exists():
        txt = frozen.read_text(encoding="utf-8", errors="replace")
        if txt.startswith("# "):
            txt = "\n".join(txt.splitlines()[1:]).lstrip()
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append(txt.rstrip() + "\n")
    (REPORTS / "latency_table.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("  wrote reports/latency_table.md")


def write_power(stats):
    lines = ["# Power analysis (Vivado report_power, post-route)\n"]
    lines.append("_Auto-generated by `scripts/parse_reports.py`._\n")
    lines.append("| top | total (W) | dynamic (W) | static (W) | MACs/cycle | pJ / MAC |")
    lines.append("|-----|----------:|------------:|-----------:|-----------:|---------:|")
    # MAC-rate per cycle: 16 for all sage16 tops (one MAC per PE per active cycle)
    for top, _desc in TOPS:
        s = stats[top]
        t  = s["p_total"]
        d  = s["p_dynamic"]
        st = s["p_static"]
        fm = s["fmax"]
        macs = 16
        pj = None
        if t is not None and fm is not None:
            pj = (t * 1e3) / (macs * fm)  # pJ/MAC = (W*1000) / (MAC*MHz)
        lines.append("| `{t}` | {tt} | {dd} | {ss} | {mc} | {pp} |".format(
            t=top,
            tt=fmt(t,  "{:.3f}"),
            dd=fmt(d,  "{:.3f}"),
            ss=fmt(st, "{:.3f}"),
            mc=macs,
            pp=fmt(pj, "{:.2f}"),
        ))
    lines.append("")
    lines.append("- `pJ/MAC = total_power * 1000 / (16 PEs * Fmax_MHz)`")
    lines.append("- reported at nominal VCCINT=1.0V, T=25C (Vivado defaults).")
    (REPORTS / "power.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("  wrote reports/power.md")


# one record per testbench; the TBs emit a single "...SUMMARY..." line
# (or in the legacy `tb_pcpi.v` / `tb_mmio.v` cases a 'PCPI matmul:' /
# 'MMIO matmul:' line) with the totals for that testbench. We count ONLY
# those banner lines to avoid double-counting the per-test detail rows.
RE_BANNERS = [
    # (label_regex_for_matching, label-when-printed)
    (re.compile(r"^.*SUMMARY.*pass=(\d+)\s+fail=(\d+)", re.M), "SUMMARY"),
    (re.compile(r"^\s*PCPI matmul:\s*pass=(\d+)\s+fail=(\d+)", re.M), "tb_pcpi"),
    (re.compile(r"^\s*MMIO matmul:\s*pass=(\d+)\s+fail=(\d+)", re.M), "tb_mmio"),
    (re.compile(r"^\s*total\s*:\s*pass=(\d+)\s+fail=(\d+)", re.M), "tb_reconfig"),
]

def write_regression_summary():
    log = read(BUILD / "regression.log")
    lines = ["# Regression summary\n"]
    lines.append("_Auto-generated by `scripts/parse_reports.py` from `build/regression.log`._\n")
    if log is None:
        lines.append("_No `build/regression.log` found. Run:_\n")
        lines.append("```")
        lines.append("scripts\\run_sim.bat > build\\regression.log 2>&1")
        lines.append("```")
    else:
        total_pass = 0
        total_fail = 0
        seen_spans = []
        for rx, _tag in RE_BANNERS:
            for m in rx.finditer(log):
                span = m.span()
                # avoid a match being counted twice by two different patterns
                if any(s[0] <= span[0] < s[1] for s in seen_spans):
                    continue
                seen_spans.append(span)
                total_pass += int(m.group(1))
                total_fail += int(m.group(2))
        lines.append(f"- total checks: **{total_pass + total_fail}**")
        lines.append(f"- passing    : **{total_pass}**")
        lines.append(f"- failing    : **{total_fail}**\n")
        lines.append("## Per-testbench SUMMARY banners\n")
        lines.append("```")
        # match a line that either says "SUMMARY" or is a TB-level totals line
        for m in re.finditer(r"^.*(?:SUMMARY|PCPI matmul:|MMIO matmul:|\btotal\s*:).*$",
                             log, re.M):
            ln = m.group(0).rstrip()
            if ln.strip():
                lines.append(ln)
        lines.append("```")
    (REPORTS / "regression_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("  wrote reports/regression_summary.md")


def main():
    REPORTS.mkdir(exist_ok=True)
    print("parse_reports.py -- consolidating Vivado + sim artefacts")
    stats = {top: collect(top) for top, _ in TOPS}
    write_area_comparison(stats)
    write_latency_table()
    write_power(stats)
    write_regression_summary()
    print("done.")


if __name__ == "__main__":
    main()
