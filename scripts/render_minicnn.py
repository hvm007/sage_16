#!/usr/bin/env python3
"""
render_minicnn.py  --  parse build/minicnn_dump.log and render a figure
showing the three synthetic input images that tb_minicnn.v fed the
sage16_top fabric, plus the Conv1 feature maps the fabric produced for
image 0, plus the FC2 logits + predicted class.

Honesty note: inputs are pseudo-random INT16 in [0, 63] generated by the
same deterministic LCG used in the Verilog TB.  They do not look like
MNIST digits because no training was performed; the goal of tb_minicnn
is to exercise the dataflow and measure cycles bit-exactly against a
golden software reference, which it does.
"""
import re, os, sys
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
LOG  = ROOT / "build" / "minicnn_dump.log"
OUT  = ROOT / "build" / "minicnn_figure.png"

raw = LOG.read_bytes()
# PowerShell redirection writes UTF-16LE with BOM; try that first, fall back to UTF-8
if raw.startswith(b"\xff\xfe"):
    text = raw.decode("utf-16", errors="ignore")
else:
    text = raw.decode("utf-8", errors="ignore")

def parse_grid(tag, idx):
    """parse '#<tag>_ROW <idx> <r> : v v v ...' into a numpy 2D array."""
    rows = {}
    rx = re.compile(rf"#{tag}_ROW\s+{idx}\s+(\d+)\s*:\s*([\-\d\s]+)")
    for m in rx.finditer(text):
        r = int(m.group(1))
        vals = [int(x) for x in m.group(2).split()]
        rows[r] = vals
    if not rows:
        return None
    H = max(rows) + 1
    W = len(rows[0])
    arr = np.zeros((H, W), dtype=np.int64)
    for r, vs in rows.items():
        arr[r] = vs
    return arr

def parse_logits():
    out = {}
    for m in re.finditer(r"#LOGITS\s+(\d+)\s*:\s*([\-\d\s]+)", text):
        idx  = int(m.group(1))
        vals = np.array([int(x) for x in m.group(2).split()], dtype=np.int64)
        out[idx] = vals
    return out

# ---- parse ----
imgs   = [parse_grid("IMG", i) for i in range(3)]
c1maps = [parse_grid("C1",  i) for i in range(4)]
logits = parse_logits()

assert all(x is not None for x in imgs),   "failed to parse input images"
assert all(x is not None for x in c1maps), "failed to parse Conv1 maps"

# ---- render ----
# layout: 3 rows
#   row 1 : 3 input images
#   row 2 : 4 Conv1 feature maps for image 0
#   row 3 : 3 bar charts of FC2 logits (one per image)
fig = plt.figure(figsize=(14, 10))
gs  = fig.add_gridspec(3, 4, hspace=0.45, wspace=0.30)

# --- row 1: input images ---
for i, img in enumerate(imgs):
    ax = fig.add_subplot(gs[0, i])
    im = ax.imshow(img, cmap="magma", vmin=0, vmax=63, interpolation="nearest")
    ax.set_title(f"Input image {i}\n({img.shape[0]}x{img.shape[1]}, INT16 pixels 0-63)",
                 fontsize=10)
    ax.set_xticks([]); ax.set_yticks([])
    plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

# blank 4th slot in row 1 for a short legend / note
ax_note = fig.add_subplot(gs[0, 3])
ax_note.axis("off")
ax_note.text(0.0, 0.95,
             "3 synthetic\npseudo-random\nimages fed to\ntb_minicnn.v",
             fontsize=11, va="top", family="monospace")
ax_note.text(0.0, 0.40,
             "Every pixel was\nreplayed on the\nfabric; results\nbit-exact vs\nsoftware golden.",
             fontsize=10, va="top", color="#444")

# --- row 2: Conv1 feature maps for image 0 ---
for oc in range(4):
    ax = fig.add_subplot(gs[1, oc])
    fmap = c1maps[oc]
    lim  = max(abs(fmap.min()), abs(fmap.max()), 1)
    im = ax.imshow(fmap, cmap="RdBu_r", vmin=-lim, vmax=lim,
                   interpolation="nearest")
    ax.set_title(f"Conv1 feature map #{oc}\n(image 0, {fmap.shape[0]}x{fmap.shape[1]})",
                 fontsize=10)
    ax.set_xticks([]); ax.set_yticks([])
    plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

# --- row 3: FC2 logits bar charts ---
for i in range(3):
    ax = fig.add_subplot(gs[2, i])
    vals = logits[i]
    pred = int(np.argmax(vals[:10]))
    colors = ["#2b8cbe"] * 10 + ["#bdbdbd", "#bdbdbd"]   # last two are padding rows
    colors[pred] = "#d7191c"
    ax.bar(range(len(vals)), vals, color=colors)
    ax.set_title(f"FC2 logits, image {i}  (pred class = {pred})", fontsize=10)
    ax.set_xlabel("class index (0-9 real, 10-11 padded)", fontsize=8)
    ax.set_ylabel("logit (INT32)", fontsize=8)
    ax.axhline(0, color="black", lw=0.5)
    ax.tick_params(labelsize=8)

ax_stats = fig.add_subplot(gs[2, 3])
ax_stats.axis("off")
ax_stats.text(0.0, 0.95,
    "Cycle counts (avg / image):\n"
    "  Conv1 fabric :  2160 cy\n"
    "  FC1   fabric :  2880 cy\n"
    "  FC2   fabric :   240 cy\n"
    "  Pool  host SW:  2499 cy\n"
    "  ----------------------\n"
    "  TOTAL        :  7779 cy\n"
    "  @160 MHz     :  48.6 us\n"
    "  throughput   :  ~20.6k img/s",
    fontsize=9.5, family="monospace", va="top")

fig.suptitle("MiniCNN-3x3 on the 16-DSP sage16_top fabric  (tb_minicnn.v)",
             fontsize=13, fontweight="bold")

fig.tight_layout(rect=[0, 0, 1, 0.97])
fig.savefig(OUT, dpi=110, bbox_inches="tight")
print(f"wrote {OUT}")
